#!/usr/bin/env python3
"""Generate tests/dotnet/ManyLocalsAndArgs.cs: a method with 300 locals and one with 270 arguments,
which compilers must encode with the two-byte ldloc/stloc/ldloca and ldarg/starg/ldarga forms
(the one-byte forms only reach index 255). Regenerate with: python3 tests/gen_many_locals.py
"""
import os
NL, NA = 300, 270
o = []
w = o.append
w("// GENERATED by tests/gen_many_locals.py -- do not edit.")
w("using System;")
w("")
w("class Program {")
w("    static void Bump(ref int x) { x += 1000; }")
w("    static volatile int vstat;")
w("    volatile int vinst;")
w("    volatile bool vflag;")
w("")
w("    static int Locals() {")
for i in range(NL): w("        int v%d = %d;" % (i, i))
w("        Bump(ref v299);                // ldloca with a two-byte index")
w("        Bump(ref v270);")
w("        v280 = v280 * 2;               // stloc / ldloc with two-byte indexes")
w("        int sum = 0;")
for i in range(NL): w("        sum += v%d;" % i)
w("        return sum;")
w("    }")
w("")
w("    static int Args(%s) {" % ", ".join("int a%d" % i for i in range(NA)))
w("        Bump(ref a269);                // ldarga with a two-byte index")
w("        a265 = a265 + 7;               // starg / ldarg with two-byte indexes")
w("        int sum = 0;")
for i in range(NA): w("        sum += a%d;" % i)
w("        return sum;")
w("    }")
w("")
w("    public static int Main() {")
w("        // sum 0..299 = 44850; +1000 +1000 for the two Bump calls; +280 for the doubled v280")
w("        if (Locals() != 44850 + 2000 + 280) return 1;")
w("        // args are 0..269: sum = 36315; +1000 (Bump) +7")
w("        if (Args(%s) != 36315 + 1000 + 7) return 2;" % ", ".join(str(i) for i in range(NA)))
w("")
w("        // volatile fields (the volatile. prefix and the IsVolatile modifier)")
w("        vstat = 5;")
w("        Program p = new Program();")
w("        p.vinst = 7; p.vflag = true;")
w("        if (vstat != 5 || p.vinst != 7 || !p.vflag) return 3;")
w("        vstat++; p.vinst += 3;")
w("        if (vstat != 6 || p.vinst != 10) return 4;")
w("        return 0;")
w("    }")
w("}")
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "dotnet", "ManyLocalsAndArgs.cs")
open(path, "w").write("\n".join(o) + "\n")
print("wrote", path, "(%d lines)" % len(o))
